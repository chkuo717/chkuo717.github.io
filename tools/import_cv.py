#!/usr/bin/env python3
"""Import the publication list from the CV section file into src/data/publications.json.

The CV file (Markdown, kept in the author's knowledge base) is the single source of truth for
the Publications page. Run this whenever that file changes, then run build.py:

    python3 tools/import_cv.py "<path to>/00 Academic Profile MD/1 CV/10 Publications.md"
    python3 build.py

What it keeps: each entry's citation as written in the CV, award notes in bold, DOIs and links.
What it drops: the CV-only material (journal metrics and citation counts in square brackets,
the promotional sentences after BC01 and in the patent notes).
"""
import html
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "data", "publications.json")

SECTIONS = {
    "Books": ("books", "Books"),
    "Book Chapters": ("chapters", "Book chapters"),
    "Journal Articles": ("journals", "Journal articles"),
    "Conference Presentations": ("conferences", "Conference papers"),
    "Patents (US patents only)": ("patents", "US patents"),
    "Theses": ("theses", "Theses"),
}

ME = "Kuo, C.-H."


def clean(text, key):
    text = re.sub(r"\s*\^\S+\s*$", "", text)                                   # block id
    text = re.sub(r"\s*\[(?:JIF|Not JCR)[^\]]*\]", "", text)                    # metrics, citation counts
    if key == "BC01":
        text = text.split("Invited contribution.")[0] + "Invited contribution."
    text = re.sub(r"\(Technology transferred to ([^—)]+?)\s+—[^)]*\)", r"(Technology transferred to \1.)", text)
    return text.strip()


def to_html(text):
    # pull URLs out before escaping, put them back as links
    urls = []
    def keep(m):
        urls.append(m.group(0).rstrip(".,;)"))
        tail = m.group(0)[len(urls[-1]):]
        return f"\x00{len(urls) - 1}\x00{tail}"
    text = re.sub(r"https?://\S+", keep, text)
    text = text.replace("\\*", "\x01")                                         # corresponding-author mark
    s = html.escape(text, quote=False)
    s = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", s)
    s = re.sub(r"\*(.+?)\*", r"<em>\1</em>", s)
    s = s.replace("\x01", "*").replace("\\", "")
    if s.count(ME) == 1:                                                        # bold the author only when unambiguous
        s = s.replace(ME, f'<b class="me">{ME}</b>')
    def link(m):
        u = urls[int(m.group(1))]
        label = "doi:" + u.split("doi.org/", 1)[1] if "doi.org/" in u else html.escape(u.split("//", 1)[1])
        return f'<a href="{html.escape(u)}">{label}</a>'
    s = re.sub(r"\x00(\d+)\x00", link, s)
    return s


def main(path):
    src = open(path, encoding="utf-8").read()
    data = {"_comment": "Generated by tools/import_cv.py from the CV section file '10 Publications.md'. Do not edit by hand.",
            "sections": []}
    sec = None
    for line in src.splitlines():
        h = re.match(r"^## (.+)$", line)
        if h:
            name = h.group(1).strip()
            sec = None
            if name in SECTIONS:
                sid, label = SECTIONS[name]
                sec = {"id": sid, "label": label, "items": []}
                data["sections"].append(sec)
            continue
        if sec is None or not line.startswith("- **"):
            continue
        m = re.match(r"^- \*\*(?:\\\[\[\[[^|\]]+\|([^\]]+)\]\]\\\]|\[([^\]]+)\])\*\*\s*(.+)$", line)
        if not m:
            raise SystemExit(f"cannot parse: {line[:80]}")
        key = m.group(1) or m.group(2)
        body = clean(m.group(3), key)
        year = re.findall(r"\b(?:19|20)\d\d\b", re.sub(r"https?://\S+|ISBN[^)]*", "", body))
        sec["items"].append({"key": key, "year": int(year[-1]) if year else None, "html": to_html(body)})
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print(", ".join(f'{s["label"]} {len(s["items"])}' for s in data["sections"]))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
